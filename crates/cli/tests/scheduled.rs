//! Real standalone CLI processes; no Desktop or Bridge is started.
use axum::{routing::post, Json, Router};
use serde_json::{json, Value};
use std::{
    path::Path,
    process::Stdio,
    sync::{
        atomic::{AtomicUsize, Ordering},
        Arc,
    },
    time::Duration,
};
use tokio::process::Command;

fn cli(data: &Path, project: &Path) -> Command {
    let mut command = Command::new(env!("CARGO_BIN_EXE_claude-code"));
    command
        .arg("--data-dir")
        .arg(data)
        .current_dir(project)
        .kill_on_drop(true);
    command
}
async fn run(data: &Path, project: &Path, args: &[&str]) -> Value {
    let output = tokio::time::timeout(
        Duration::from_secs(20),
        cli(data, project).args(args).output(),
    )
    .await
    .unwrap()
    .unwrap();
    assert!(
        output.status.success(),
        "{}",
        String::from_utf8_lossy(&output.stderr)
    );
    serde_json::from_slice(&output.stdout).unwrap()
}

#[tokio::test]
async fn standalone_cron_host_generates_and_second_process_stops_pending_request() {
    let dir = tempfile::tempdir().unwrap();
    let project = dir.path().join("project");
    let data = dir.path().join("data");
    std::fs::create_dir(&project).unwrap();
    std::fs::create_dir(&data).unwrap();
    let listener = tokio::net::TcpListener::bind("127.0.0.1:0").await.unwrap();
    std::fs::write(data.join("providers.json"),json!([{"id":"fixture","name":"Fixture","base_url":format!("http://{}",listener.local_addr().unwrap()),"api_key":"fixture","api_format":"openai","enabled":true,"models":[{"id":"model","name":"Fixture","enabled":true,"supports_vision":false,"supports_web_search":false}]}]).to_string()).unwrap();
    let calls = Arc::new(AtomicUsize::new(0));
    let fixture_calls = calls.clone();
    let app=Router::new().route("/v1/chat/completions",post(move |Json(body):Json<Value>|{let calls=fixture_calls.clone();async move{
        assert!(body.get("tools").is_none());assert!(body["messages"].to_string().contains("scheduled fixture"));
        if calls.fetch_add(1,Ordering::SeqCst)>0{std::future::pending::<()>().await;}
        Json(json!({"id":"r","object":"chat.completion","created":0,"model":"model","choices":[{"index":0,"message":{"role":"assistant","content":"Generated by independent CLI host."},"finish_reason":"stop"}]}))
    }}));
    let server = tokio::spawn(async move { axum::serve(listener, app).await.unwrap() });
    let record = run(
        &data,
        &project,
        &["cron", "create", "* * * * * *", "scheduled fixture"],
    )
    .await;
    let id = record["cron_id"].as_str().unwrap();
    let mut host = cli(&data, &project)
        .args(["cron", "host", "--provider", "fixture", "--model", "model"])
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .spawn()
        .unwrap();
    tokio::time::timeout(Duration::from_secs(15), async {
        loop {
            let state = run(&data, &project, &["cron", "get", id]).await;
            if state["output"] == "Generated by independent CLI host." {
                break;
            }
            tokio::time::sleep(Duration::from_millis(50)).await;
        }
    })
    .await
    .unwrap();
    let duplicate = tokio::time::timeout(
        Duration::from_secs(10),
        cli(&data, &project)
            .args(["cron", "host", "--provider", "fixture", "--model", "model"])
            .output(),
    )
    .await
    .unwrap()
    .unwrap();
    assert!(!duplicate.status.success());
    tokio::time::timeout(Duration::from_secs(10), async {
        while calls.load(Ordering::SeqCst) < 2 {
            tokio::time::sleep(Duration::from_millis(25)).await;
        }
    })
    .await
    .unwrap();
    assert_eq!(
        run(&data, &project, &["cron", "stop"]).await["stopped"],
        true
    );
    assert!(tokio::time::timeout(Duration::from_secs(5), host.wait())
        .await
        .unwrap()
        .unwrap()
        .success());
    let cancelled = run(&data, &project, &["cron", "get", id]).await;
    assert_eq!(cancelled["state"], "failed");
    assert!(cancelled["error"].as_str().unwrap().contains("cancelled"));
    run(&data, &project, &["cron", "delete", id]).await;
    assert_eq!(
        run(&data, &project, &["cron", "list"]).await["tasks"],
        json!([])
    );
    server.abort();
}
